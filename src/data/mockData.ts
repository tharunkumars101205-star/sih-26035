// Helper to pre-populate realistic weighing observations for inst_01
function buildSampleWeighingRows(): any[] {
  const steps = [
    { load: 0.0, indicated: 0.0, dir: 'increasing' },
    { load: 0.1, indicated: 0.1, dir: 'increasing' }, // Min
    { load: 1.0, indicated: 1.0, dir: 'increasing' },
    { load: 2.5, indicated: 2.5, dir: 'increasing' }, // 500e = 2.5kg (MPE bracket boundary)
    { load: 5.0, indicated: 5.0, dir: 'increasing' },
    { load: 7.5, indicated: 7.5, dir: 'increasing' }, // 0.5 Max
    { load: 10.0, indicated: 10.005, dir: 'increasing' }, // 2000e = 10.0kg
    { load: 12.5, indicated: 12.505, dir: 'increasing' },
    { load: 15.0, indicated: 15.005, dir: 'increasing' }, // Max
    // Decreasing
    { load: 12.5, indicated: 12.505, dir: 'decreasing' },
    { load: 10.0, indicated: 10.0, dir: 'decreasing' },
    { load: 7.5, indicated: 7.5, dir: 'decreasing' },
    { load: 2.5, indicated: 2.5, dir: 'decreasing' },
    { load: 0.1, indicated: 0.1, dir: 'decreasing' },
    { load: 0.0, indicated: 0.0, dir: 'decreasing' },
  ];

  return steps.map((s, idx) => {
    const calc = calculateWeighingError(s.load, s.indicated, 0.005, 'III', undefined, 0.0);
    return {
      id: `w_row_${idx + 1}`,
      stepNumber: idx + 1,
      load: s.load,
      loadInE: parseFloat((s.load / 0.005).toFixed(1)),
      direction: s.dir,
      indicatedLoad: s.indicated,
      actualWeightCalculated: calc.calculatedP,
      error: calc.errorE,
      correctedError: calc.correctedErrorEc,
      mpeForLoad: calc.mpeAllowable,
      compliance: calc.verdict,
    };
  });
}

